using System;
using System.IO;
using System.Security.Cryptography;

namespace MirrorControl;

/// <summary>
/// Prevents accidental launch of a different UxPlay executable in the opt-in
/// test build. The embedded hash binds our controller to the bundled receiver.
/// This is build-integrity checking, not malware certification or code signing.
/// </summary>
internal static class ReceiverIdentity
{
    internal static string BundledPath => Path.Combine(AppContext.BaseDirectory, "native", "bin", "uxplay.exe");

    internal static void Validate(string executable)
    {
        if (BackendSecurityGate.IsBlocked)
            throw new InvalidOperationException(BackendSecurityGate.Reason);

#if EXPERIMENTAL_RECEIVER
        string bundled = Path.GetFullPath(BundledPath);
        if (!string.Equals(Path.GetFullPath(executable), bundled, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Only the exact UxPlay bundled with this test build may be started.");
        if (!File.Exists(bundled))
            throw new FileNotFoundException("The pinned experimental receiver is missing.", bundled);
        // Generated by the CI test-package job at build time, from the binary it
        // just built. Never let the app accept arbitrary user-supplied hashes.
        string actual = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(bundled)));
        if (!string.Equals(actual, ExperimentalBuildIdentity.UxPlaySha256, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Bundled receiver checksum mismatch. Do not run this package.");
        string patch = Path.Combine(AppContext.BaseDirectory, "native", "source-notices", "applied-source-diff.patch");
        if (!File.Exists(patch))
            throw new InvalidOperationException("Required corresponding-source patch is missing from the test bundle.");
#else
        throw new InvalidOperationException(BackendSecurityGate.Reason);
#endif
    }
}
